function initial() {
  try {
    const saved = localStorage.getItem('locale')
    if (saved in messages) return saved
  } catch {}
  return navigator.language?.startsWith('en') ? 'en' : 'nl'
}

export const locale = ref(initial())

export function setLocale(l) {
  locale.value = l
  try {
    localStorage.setItem('locale', l)
  } catch {}
  document.documentElement.lang = l
}

// t('items', 3) → "3 items". Reactive: reads locale inside templates.
export function t(key, ...args) {
  const m = messages[locale.value][key] ?? messages.en[key] ?? key
  return typeof m === 'function' ? m(...args) : m
}
